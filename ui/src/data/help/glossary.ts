export function getGlossary(t: TFunction<'help'>): GlossaryEntry[] {
  return (Object.keys(glossaryRelated) as GlossaryId[]).map((id) => ({
    term: t(`glossary.entries.${id}.term`),
    fullName: t(`glossary.entries.${id}.fullName`),
    category: t(`glossary.entries.${id}.category`),
    techDef: t(`glossary.entries.${id}.techDef`),
    laymanDef: t(`glossary.entries.${id}.laymanDef`),
    related: glossaryRelated[id].map((key) => t(`glossary.entries.${key}.term`)),
  }));
}
